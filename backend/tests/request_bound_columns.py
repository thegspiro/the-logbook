"""Request fields bounded to the column they are stored in, and the ones that are not.

Read by ``test_request_numeric_bounds.py``. A request field of a numeric type with no
upper bound passes validation for a value its column cannot hold, then fails at flush
as MySQL error 1264 (reported as "An unexpected error occurred"). Every such field is
either in ``COLUMN_BACKED`` -- bounded to the column named beside it, and checked against
that column's real range -- or in ``NOT_COLUMN_BACKED`` with the reason it has no column
to mirror.

Adding a request field: bound it (``app/schemas/column_bounds.py`` has the constants) and
add a ``COLUMN_BACKED`` row. A field matched to its column by name alone, where every
column of that name has the same type, is still a row; the model is one of them.

Row format: ``schema module:Class.field=Model.column``.

``POLICY_BOUNDED`` is the third list: a field a department's rules bound *below* the
column, so a typo cannot flow into every total. Its bound is checked to sit inside the
column's range (and to refuse a value past it), where ``COLUMN_BACKED`` asserts the two
are equal. Request schemas only: the ``*Base`` a response inherits keeps the column's own
range, so a row written before a policy bound still serializes.
"""

