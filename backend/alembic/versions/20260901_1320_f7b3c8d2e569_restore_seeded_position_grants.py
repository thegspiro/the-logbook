"""Restore the registry's seeded grants on positions the wizard overwrote

The onboarding position editor shows two checkboxes per module and saves what
they say. Its defaults came from a heuristic — "a member views every module
whose category is not System", "a leader manages everything but settings" —
which had no relationship to what ``DEFAULT_POSITIONS`` actually seeds. The
first Continue therefore wrote the heuristic's answer over the rows the
registry had just created: ``member`` got ``facilities.view`` and
``notifications.view`` back (two earlier migrations had removed the former),
and ``board_of_directors`` got ``.*`` on eighteen modules it is not seeded
with. ``dependencies.py`` unions every assigned position's stored
permissions, so those are live grants on every department that finished
onboarding under that code.

The wizard now presents the registry's own answer, which fixes departments
that have not onboarded yet. The endpoint refuses to run again once setup is
complete, so this is the only thing that reaches the rest.

**Matched on the whole stored list, not on the individual grants.** The old
save was a replacement, so an untouched row holds exactly the heuristic's
output — reproduced per slug in ``_REWRITES`` below. A row that differs by so
much as one permission has been edited since, and is left alone: a department
that deliberately gave its board a grant keeps it, and the cost is that its
mistaken ones survive too. That trade is the right way round — this must not
silently revoke authority somebody chose to grant. Scoped to ``is_system``
rows for the same reason (CLAUDE.md pitfall #23).

Not reversible in substance: ``downgrade`` would have to re-grant permissions
that no department asked for, which is the defect rather than a prior state
worth restoring.

Guarded on the table existing: fresh installs come up through ``create_all`` +
stamp-head rather than this chain (CLAUDE.md pitfall #26).
"""

