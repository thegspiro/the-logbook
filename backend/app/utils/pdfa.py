"""
Turn a generated record document into PDF/A-2b, the archival profile.

Certified election results, finalized evaluations and adopted minutes are
records a department keeps for years. PDF/A (ISO 19005) is the profile meant
to still render the same way decades on. Level 2b ("basic") requires the
file to be self-contained and unambiguous in appearance:

* every font embedded (``app.utils.pdf_fonts`` does that at render time);
* an output intent saying how DeviceRGB colour is to be read, here sRGB,
  generated by Pillow's littleCMS rather than shipped as a binary file;
* XMP metadata in the catalog that declares the conformance level and agrees
  with the document information dictionary (title, author, producer, dates);
* no encryption, JavaScript or external content (none of these documents
  have any).

ReportLab can do the first and last, but its catalog has no slot for an
output intent, so the document is rewritten once with pypdf (already a
dependency, for minutes attachments) to add the second and third. Writing it
through pypdf also normalizes stream framing, which veraPDF flags in
ReportLab's own output (rule 6.1.7.1-2).

Checked with veraPDF 1.28 on 2026-11-10. ``tests/test_pdfa.py`` asserts the
structural requirements above on every run, since CI does not run veraPDF.
"""

import re
from datetime import datetime, timezone
from io import BytesIO
from typing import Any, Mapping, Optional
from xml.sax.saxutils import escape

from PIL import ImageCms
from pypdf import PdfReader, PdfWriter
from pypdf.generic import (
    ArrayObject,
    DecodedStreamObject,
    DictionaryObject,
    NameObject,
    NumberObject,
    TextStringObject,
)

PDFA_PART = 2
PDFA_CONFORMANCE = "B"
PRODUCER = "The Logbook"
_SRGB = "sRGB IEC61966-2.1"

_PDF_DATE = re.compile(
    r"D:(\d{4})(\d{2})?(\d{2})?(\d{2})?(\d{2})?(\d{2})?"
    r"(?:(Z)|([+-])(\d{2})'?(\d{2})?'?)?"
)


def _srgb_profile() -> bytes:
    return ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes()


def _xmp_date(pdf_date: str) -> str:
    """A PDF date string (``D:20261110093000+00'00'``) as an XMP date.

    PDF/A requires the two to describe the same instant.
    """
    m = _PDF_DATE.match(pdf_date)
    if not m:
        raise ValueError(f"Unreadable PDF date: {pdf_date!r}")
    year, month, day, hour, minute, second = (
        m.group(1),
        m.group(2) or "01",
        m.group(3) or "01",
        m.group(4) or "00",
        m.group(5) or "00",
        m.group(6) or "00",
    )
    if m.group(8):
        zone = f"{m.group(8)}{m.group(9)}:{m.group(10) or '00'}"
    else:
        zone = "Z"
    return f"{year}-{month}-{day}T{hour}:{minute}:{second}{zone}"


def _pdf_date(moment: datetime) -> str:
    return moment.strftime("D:%Y%m%d%H%M%S+00'00'")


def _xmp(
    *,
    title: str,
    author: Optional[str],
    created: str,
    modified: str,
    creator_tool: str,
) -> bytes:
    creator = (
        f"<dc:creator><rdf:Seq><rdf:li>{escape(author)}</rdf:li></rdf:Seq>"
        "</dc:creator>"
        if author
        else ""
    )
    packet = f"""<?xpacket begin="﻿" id="W5M0MpCehiHzreSzNTczkc9d"?>
<x:xmpmeta xmlns:x="adobe:ns:meta/">
 <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
  <rdf:Description rdf:about=""
    xmlns:dc="http://purl.org/dc/elements/1.1/"
    xmlns:xmp="http://ns.adobe.com/xap/1.0/"
    xmlns:pdf="http://ns.adobe.com/pdf/1.3/"
    xmlns:pdfaid="http://www.aiim.org/pdfa/ns/id/">
   <dc:format>application/pdf</dc:format>
   <dc:title><rdf:Alt><rdf:li xml:lang="x-default">{escape(title)}</rdf:li></rdf:Alt></dc:title>
   {creator}
   <xmp:CreateDate>{_xmp_date(created)}</xmp:CreateDate>
   <xmp:ModifyDate>{_xmp_date(modified)}</xmp:ModifyDate>
   <xmp:CreatorTool>{escape(creator_tool)}</xmp:CreatorTool>
   <pdf:Producer>{PRODUCER}</pdf:Producer>
   <pdfaid:part>{PDFA_PART}</pdfaid:part>
   <pdfaid:conformance>{PDFA_CONFORMANCE}</pdfaid:conformance>
  </rdf:Description>
 </rdf:RDF>
</x:xmpmeta>
<?xpacket end="w"?>"""
    return packet.encode("utf-8")


# Annotation flag bits (ISO 32000-1, 12.5.3).
_HIDDEN_FLAGS = 1 | 2 | 32  # Invisible, Hidden, NoView
_PRINT_FLAG = 4


def _flag_annotations_printable(writer: PdfWriter) -> None:
    """PDF/A requires every annotation to carry its flags, with Print set and
    the hidden bits clear. ReportLab writes the links in rich-text minutes
    without any flags at all (veraPDF rule 6.3.2-1)."""
    for page in writer.pages:
        annots = page.get("/Annots")
        if not annots:
            continue
        for ref in annots.get_object():
            annot = ref.get_object()
            if annot.get("/Subtype") == "/Popup":
                continue
            flags = int(annot.get("/F", 0))
            annot[NameObject("/F")] = NumberObject(
                (flags | _PRINT_FLAG) & ~_HIDDEN_FLAGS
            )


def to_pdfa(pdf: bytes) -> bytes:
    """Return *pdf* rewritten as PDF/A-2b.

    The title and author are taken from the document information dictionary
    the renderer wrote, so the XMP cannot disagree with it.
    """
    reader = PdfReader(BytesIO(pdf))
    if reader.is_encrypted:
        raise ValueError("An encrypted PDF cannot be made PDF/A")
    writer = PdfWriter(clone_from=reader)

    info: Mapping[str, Any] = reader.metadata or {}
    title = str(info.get("/Title") or "")
    author = str(info.get("/Author") or "") or None
    creator_tool = str(info.get("/Creator") or PRODUCER)
    now = _pdf_date(datetime.now(timezone.utc))
    created = str(info.get("/CreationDate") or now)
    # The rewrite is the last modification; the info dictionary and the XMP
    # both say so.
    writer.add_metadata(
        {
            "/Title": title,
            "/Producer": PRODUCER,
            "/Creator": creator_tool,
            "/CreationDate": created,
            "/ModDate": now,
            **({"/Author": author} if author else {}),
        }
    )

    metadata = DecodedStreamObject()
    metadata.set_data(
        _xmp(
            title=title,
            author=author,
            created=created,
            modified=now,
            creator_tool=creator_tool,
        )
    )
    # PDF/A forbids a filter on the metadata stream: archival tools must be
    # able to read it without decoding.
    metadata[NameObject("/Type")] = NameObject("/Metadata")
    metadata[NameObject("/Subtype")] = NameObject("/XML")
    writer.root_object[NameObject("/Metadata")] = writer._add_object(metadata)

    _flag_annotations_printable(writer)

    profile = DecodedStreamObject()
    profile.set_data(_srgb_profile())
    profile[NameObject("/N")] = NumberObject(3)
    intent = DictionaryObject(
        {
            NameObject("/Type"): NameObject("/OutputIntent"),
            NameObject("/S"): NameObject("/GTS_PDFA1"),
            NameObject("/OutputConditionIdentifier"): TextStringObject(_SRGB),
            NameObject("/Info"): TextStringObject(_SRGB),
            NameObject("/DestOutputProfile"): writer._add_object(profile),
        }
    )
    writer.root_object[NameObject("/OutputIntents")] = ArrayObject(
        [writer._add_object(intent)]
    )

    out = BytesIO()
    writer.write(out)
    return out.getvalue()
